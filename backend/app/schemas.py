"""Request validation models (Pydantic)."""
from datetime import date
from typing import Annotated, Literal, Optional

from pydantic import BaseModel, StringConstraints

DefectType = Literal["Weave Defect", "Shade Variation", "Hole/Tear", "Count Deviation", "Other"]
Severity = Literal["Critical", "Major", "Minor"]
Status = Literal["Open", "Resolved"]

MachineId = Annotated[str, StringConstraints(strip_whitespace=True, min_length=1, max_length=50)]
Remarks = Annotated[str, StringConstraints(strip_whitespace=True, max_length=1000)]
Note = Annotated[str, StringConstraints(strip_whitespace=True, min_length=1, max_length=1000)]


class InspectionCreate(BaseModel):
    inspection_date: date
    machine_id: MachineId
    defect_type: DefectType
    severity: Severity
    remarks: Optional[Remarks] = None
    # Optional idempotency key generated by the client so offline retries never duplicate.
    client_id: Optional[Annotated[str, StringConstraints(min_length=8, max_length=64)]] = None


class ResolveRequest(BaseModel):
    resolution_note: Note


class SapPayload(BaseModel):
    """Mocked SAP QM notification. See README for an example."""
    notification_id: Annotated[str, StringConstraints(strip_whitespace=True, min_length=1, max_length=40)]
    inspection_date: date
    work_center: MachineId
    defect_code: Annotated[str, StringConstraints(strip_whitespace=True, max_length=20)] = ""
    severity: Severity
    text: Optional[Remarks] = None
